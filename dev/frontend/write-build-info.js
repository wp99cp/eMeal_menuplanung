/**
 * Writes frontend/src/build.ts, as `angular-build-info` does for the other builds.
 * Inside the container there is no git repository, the git infos are passed by /dev/compose.sh
 */

const fs = require('fs');
const path = require('path');

const frontend = path.join(__dirname, '../../frontend');
const hash = process.env.BUILD_GIT_HASH || 'unknown';

const build = {
    version: require(path.join(frontend, 'package.json')).version,
    timestamp: new Date().toString(),
    message: null,
    git: {
        user: null,
        branch: process.env.BUILD_GIT_BRANCH || 'unknown',
        hash: hash.substring(0, 6),
        fullHash: hash
    }
};

fs.writeFileSync(path.join(frontend, 'src/build.ts'),
    '// Build information, generated by /dev/frontend/write-build-info.js\n' +
    'const build = ' + JSON.stringify(build, null, 4) + ';\n\nexport default build;\n');
